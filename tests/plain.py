"""Текст для сравнения в тестах: суммы с обычными пробелами.

logic.money ставит неразрывные пробелы (NBSP) между разрядами и перед «₽»,
чтобы «2 107 700 ₽» не переносилось посреди числа. Тесты пишут суммы так,
как их читает человек, и сверяют смысл, а не типографику: страницы
(WebCase.get_ok), сообщения бота (FakeBot, FakeSession.sent) и строки
логики сравниваются через plain(). Сам неразрывный пробел проверяют
отдельно: TestMoney в test_crm_logic, страница и сообщение - по сырым
байтам, выгрузки - на его отсутствие в числах.
"""

from __future__ import annotations

NBSP = " "


def plain(text: str | None) -> str | None:
    """NBSP -> обычный пробел; None остаётся None."""
    return None if text is None else text.replace(NBSP, " ")
