def feminine(surname: str) -> str:
    """Женская форма фамилии: все фамилии списка на -ов/-ев/-ин."""
    return surname + "а"


class People:
    """Раздатчик имён и телефонов с памятью о выданном.

    Один на весь сид: телефон клиента уникален в базе, и модуль сервиса,
    заводящий сторонних клиентов, обязан брать номера из того же
    раздатчика, а не придумывать свои.
    """

    def __init__(self, rng: random.Random) -> None:
        self.rng = rng
        self.phones: set[str] = set()
        self.names: set[str] = set()

    def phone(self) -> str:
        """+7 000 0XX XX XX в формате панели (+7XXXXXXXXXX). Случайное число
        то же, что было у прежнего диапазона: мир сида от смены кода не
        меняется, меняются только сами номера."""
        while True:
            phone = "+70000" + f"{self.rng.randrange(1_000_000):06d}"
            if phone not in self.phones:
                self.phones.add(phone)
                return phone

    def name(self, *, female: bool | None = None) -> str:
        """ФИО; повтор тройки допустим в жизни, но в демо путает - избегаем."""
        rng = self.rng
        if female is None:
            female = rng.random() < 0.12
        for _ in range(50):
            surname = rng.choice(SURNAMES)
            patronymic = rng.choice(PATRONYMICS)
            if female:
                first = rng.choice(FEMALE_NAMES)
                surname = feminine(surname)
                patronymic = patronymic[:-4] + "овна" if patronymic.endswith("ович") \
                    else patronymic[:-4] + "евна"
            else:
                first = rng.choice(MALE_NAMES)
            full = f"{surname} {first} {patronymic}"
            if full not in self.names:
                self.names.add(full)
                return full
        self.names.add(full)
        return full

    def person(self, *, female: bool | None = None) -> tuple[str, str]:
        return self.name(female=female), self.phone()
