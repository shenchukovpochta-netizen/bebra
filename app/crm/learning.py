@dataclass(frozen=True)
class Step:
    """Шаг маршрута. url - куда вести, с подстановками {client}, {rental},
    {bike}, {order} из фактов; fallback - пока нужной записи ещё нет."""

    code: str
    title: str
    how: str
    why: str
    url: str
    fallback: str


@dataclass(frozen=True)
class Track:
    code: str
    title: str
    profile: str
    lead: str
    steps: tuple[Step, ...]


