TRACK_OF_PROFILE: dict[str, str] = {t.profile: code for code, t in TRACKS.items()}


def track_of(staff: Mapping[str, Any] | None) -> str | None:
    """Маршрут учебного сотрудника по коду профиля; None - не ученик."""
    return TRACK_OF_PROFILE.get(str((staff or {}).get("profile_code") or ""))


def actor(staff: Mapping[str, Any]) -> str:
    """Подпись записей сотрудника - та же, что ставит панель (who)."""
    return f"staff:{staff['login']}"


def kit_code(login: str) -> str | None:
    """Номер учебного велосипеда по логину ученика; None - не ученик."""
    if not login.startswith(LOGIN_PREFIX):
        return None
    number = login[len(LOGIN_PREFIX):]
    return KIT_PREFIX + number if number.isdigit() else None


def kit_model(tariffs: Iterable[Mapping[str, Any]],
              models: Iterable[Mapping[str, Any]]) -> str | None:
    """Модель учебного велосипеда: та, у которой есть недельный тариф, -
    иначе выдача откажет «нет тарифа на 7 дн.». Без цен по моделям -
    любая из каталога: тогда работает запасной тариф."""
    for t in tariffs:
        if (t.get("active", True) and (t.get("kind") or "bike") == "bike"
                and int(t.get("period_days") or 0) == 7 and t.get("model")):
            return str(t["model"])
    return next((str(m["title"]) for m in models if m.get("title")), None)


def _url(step: Step, facts: Mapping[str, Any]) -> str:
    """Адрес шага с подстановкой. Нет записи для пути - запасной адрес;
    для параметра - параметр выпадает (выдача без клиента или без
    велосипеда всё равно открывается)."""
    keys = {"client": facts.get("client_id"), "rental": facts.get("rental_id"),
            "bike": facts.get("bike_id"), "order": facts.get("order_id"),
            "kit": facts.get("kit_id")}
    path, _, query = step.url.partition("?")
    if any("{" + k + "}" in path and keys[k] is None for k in keys):
        return step.fallback
    path = path.format(**{k: v for k, v in keys.items() if "{" + k + "}" in path})
    params = []
    for pair in filter(None, query.split("&")):
        name, _, value = pair.partition("=")
        holes = [k for k in keys if "{" + k + "}" in value]
        if any(keys[k] is None for k in holes):
            continue
        params.append(f"{name}={value.format(**{k: keys[k] for k in holes})}")
    return path + ("?" + "&".join(params) if params else "")


def progress(track: str, facts: Mapping[str, Any]) -> dict[str, Any]:
    """Шаги маршрута с отметками по фактам базы.

    Текущий - первый невыполненный: по порядку проще, но сделанное
    раньше срока засчитывается сразу - навык есть, и заставлять делать
    его второй раз незачем.
    """
    spec = TRACKS[track]
    steps = [{"code": s.code, "title": s.title, "how": s.how, "why": s.why,
              "url": _url(s, facts), "done": bool(facts.get(s.code))}
             for s in spec.steps]
    current = next((s for s in steps if not s["done"]), None)
    done = sum(1 for s in steps if s["done"])
    for i, s in enumerate(steps, start=1):
        s["no"] = i
        s["now"] = s is current
    return {"track": track, "title": spec.title, "lead": spec.lead, "steps": steps,
            "current": current, "done": done, "total": len(steps),
            "finished": current is None}


def fresh(steps: Iterable[Mapping[str, Any]], seen: Iterable[str]) -> list[str]:
    """Заголовки шагов, выполненных с прошлой страницы: их показывают
    одной строкой «Готово», чтобы новичок видел, что действие засчитано."""
    before = set(seen)
    return [s["title"] for s in steps if s["done"] and s["code"] not in before]


def done_codes(steps: Iterable[Mapping[str, Any]]) -> list[str]:
    return [s["code"] for s in steps if s["done"]]


def trainee_name(number: int) -> str:
    """Имя учебного сотрудника: без ФИО - в демо, открытом всем, не
    должно оседать ни одного настоящего имени, и своё новичок не вводит.
    Маршрут в имя не идёт: он в меню («Обучение · 2/6») и в заголовке, а
    длинное имя обрезалось в боковой панели."""
    return f"Ученик {number}"
