"""Соглашение об использовании простой электронной подписи.

Текст собирается из реквизитов организации и данных клиента - и ровно
в том виде, в каком его приняли, сохраняется в заявке на подпись. Это
и есть предмет спора: не «шаблон, который тогда был», а конкретные
буквы, под которыми стоит код.

Формулировки опираются на ст. 160 ГК РФ, 63-ФЗ «Об электронной подписи»
(ст. 2, 5, 6, 9) и 152-ФЗ. Юрист правит текст здесь, а не в базе:
заявки хранят свои копии и задним числом не меняются.
"""

from __future__ import annotations

import hashlib
from datetime import date
from typing import Any

# Сколько хранится журнал подписаний. Три года - общий срок исковой
# давности: раньше выбрасывать нечего, позже - незачем.
KEEP_YEARS = 3

AGREEMENT = """СОГЛАШЕНИЕ ОБ ИСПОЛЬЗОВАНИИ ПРОСТОЙ ЭЛЕКТРОННОЙ ПОДПИСИ
№ {no} от {today}

{company_full}, ИНН {inn}, ОГРН/ОГРНИП {ogrn}, адрес: {address},
телефон {phone}{email_part} (далее — «Оператор»), с одной стороны, и
{client_name}, телефон {client_phone} (далее — «Пользователь»),
с другой стороны, заключили настоящее Соглашение о нижеследующем.

1. ПРЕДМЕТ СОГЛАШЕНИЯ

1.1. Соглашение устанавливает правила использования простой электронной
подписи (далее — ПЭП) при совершении юридически значимых действий
в информационной системе Оператора: на странице подписания документов
и в Telegram-боте проката.

1.2. Соглашение заключено в соответствии с п. 2 ст. 160 ГК РФ и ст. 6
Федерального закона от 06.04.2011 № 63-ФЗ «Об электронной подписи»
и определяет порядок, при котором электронный документ, подписанный
ПЭП, признаётся равнозначным документу на бумажном носителе,
подписанному собственноручной подписью.

1.3. Пользователь акцептует Соглашение получением кода подтверждения
и его корректным вводом в информационной системе Оператора.

2. ТЕРМИНЫ

2.1. Код подтверждения — числовой код, формируемый Оператором случайным
образом, направляемый Пользователю и действующий {code_minutes} минут.

2.2. Ключ ПЭП — код подтверждения, известный только Пользователю
и направленный ему по каналу связи, указанному в п. 3.1.

2.3. Электронный документ — документ, сформированный Оператором
и представленный Пользователю для подписания.

3. ПОРЯДОК ПРИМЕНЕНИЯ ПЭП

3.1. Код подтверждения направляется Пользователю в Telegram на аккаунт,
привязанный к номеру телефона Пользователя, либо сообщается Оператором
по телефону {client_phone}.

3.2. Идентификация Пользователя осуществляется по номеру телефона
и корректно введённому коду подтверждения. Стороны признают такую
идентификацию достаточной.

3.3. Для подписания Пользователь: открывает документы для ознакомления,
запрашивает код подтверждения, вводит полученный код. Корректный ввод
кода признаётся Сторонами фактом подписания перечисленных документов.

3.4. Оператор фиксирует в журнале подписаний дату и время подписания,
номер телефона, сетевой адрес и параметры устройства Пользователя,
а также хэш-суммы (SHA-256) подписанных документов. Сам код
подтверждения в журнале не хранится.

4. ПЕРЕЧЕНЬ ПОДПИСЫВАЕМЫХ ДОКУМЕНТОВ

{docs_list}

5. РАВНОЗНАЧНОСТЬ ПЭП

5.1. Электронный документ, подписанный ПЭП в порядке, установленном
настоящим Соглашением, признаётся равнозначным документу на бумажном
носителе, подписанному собственноручной подписью, и порождает
идентичные правовые последствия.

6. ОБЯЗАННОСТИ СТОРОН

6.1. Пользователь обязан не передавать код подтверждения третьим лицам
и незамедлительно уведомить Оператора об утрате телефона или контроля
над ним по телефону {phone}.

6.2. Оператор обязан обеспечить конфиденциальность журнала подписаний,
хранить подписанные документы и журнал не менее {keep_years} лет
и по требованию Пользователя предоставить их копии.

6.3. Пользователь несёт ответственность за действия, совершённые с его
кодом подтверждения до момента получения Оператором уведомления
по п. 6.1.

7. СРОК ДЕЙСТВИЯ

7.1. Соглашение вступает в силу с момента акцепта (п. 1.3) и действует
бессрочно. Любая из Сторон вправе расторгнуть его, уведомив другую
Сторону не менее чем за 30 календарных дней.

7.2. Расторжение не влечёт утраты силы документов, подписанных до даты
расторжения.

8. РЕКВИЗИТЫ ОПЕРАТОРА

{company_full}
ИНН {inn}, ОГРН/ОГРНИП {ogrn}
Адрес: {address}
Телефон: {phone}{email_line}
"""


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_agreement(company: dict[str, Any], client: dict[str, Any], *,
                    no: str, docs: list[dict], today: date | None = None,
                    code_minutes: int = 10) -> str:
    """Текст соглашения для конкретного клиента и пакета документов."""
    today = today or date.today()
    email = str(company.get("company_email") or "").strip()
    listed = "\n".join(f"— {doc['title']}" for doc in docs
                       if doc.get("kind") != "esign") or "— документы из пакета подписания"
    return AGREEMENT.format(
        no=no, today=today.strftime("%d.%m.%Y"),
        company_full=company.get("company_name") or "Оператор",
        inn=company.get("company_inn") or "—",
        ogrn=company.get("company_ogrn") or "—",
        address=company.get("company_address") or "—",
        phone=company.get("company_phone") or "—",
        email_part=f", эл. почта {email}" if email else "",
        email_line=f"\nЭл. почта: {email}" if email else "",
        client_name=client.get("full_name") or "—",
        client_phone=client.get("phone") or "—",
        docs_list=listed, code_minutes=code_minutes, keep_years=KEEP_YEARS)
